// Writes .env.docker from the running local Supabase stack, for `docker compose up` and `npm run dev:local`.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

let status;
try {
  status = JSON.parse(execFileSync("npx", ["supabase", "status", "-o", "json"], { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] }));
} catch {
  console.error("Local Supabase isn't running. Start it with `npm run db:start`, then run this again.");
  process.exit(1);
}

const publishable = status.PUBLISHABLE_KEY ?? status.ANON_KEY;
const secret = status.SECRET_KEY ?? status.SERVICE_ROLE_KEY;
if (!status.API_URL || !publishable || !secret) {
  console.error("`supabase status` didn't report an API URL and keys:", Object.keys(status).join(", "));
  process.exit(1);
}

const appPort = process.env.APP_PORT ?? "3000";
const lines = [
  "# Generated by `npm run env:docker` from the local Supabase stack. Safe to regenerate; don't commit.",
  `NEXT_PUBLIC_SUPABASE_URL=${status.API_URL}`,
  `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${publishable}`,
  `SUPABASE_SECRET_KEY=${secret}`,
  `NEXT_PUBLIC_SITE_URL=http://localhost:${appPort}`,
  "NEXT_PUBLIC_MEMBER_EMAIL_SIGNIN=true",
  "",
];
writeFileSync(".env.docker", lines.join("\n"));
console.log(`Wrote .env.docker (Supabase at ${status.API_URL}). Sign-in emails: ${status.INBUCKET_URL ?? status.MAILPIT_URL ?? "http://127.0.0.1:54324"}`);
